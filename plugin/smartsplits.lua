if vim.env.HERDR_ENV == "1" then
    vim.pack.add(require("load").gh({ "lmilojevicc/herdr-splits.nvim" }))
    require("herdr-splits").setup({
        nav_keys = { left = "<C-h>", down = "<C-j>", up = "<C-k>", right = "<C-l>" },
        resize_keys = { left = "<C-S-h>", down = "<C-S-j>", up = "<C-S-k>", right = "<C-S-l>" },
    })

    vim.keymap.set("n", "<C-h>", function()
        require("herdr-splits").move_cursor_left()
    end, { desc = "herdr-splits - navigate left" })
    vim.keymap.set("n", "<C-j>", function()
        require("herdr-splits").move_cursor_down()
    end, { desc = "herdr-splits - navigate down" })
    vim.keymap.set("n", "<C-k>", function()
        require("herdr-splits").move_cursor_up()
    end, { desc = "herdr-splits - navigate up" })
    vim.keymap.set("n", "<C-l>", function()
        require("herdr-splits").move_cursor_right()
    end, { desc = "herdr-splits - navigate right" })
    vim.keymap.set("n", "<C-S-h>", function()
        require("herdr-splits").resize_left()
    end, { desc = "herdr-splits - resize left" })
    vim.keymap.set("n", "<C-S-j>", function()
        require("herdr-splits").resize_down()
    end, { desc = "herdr-splits - resize down" })
    vim.keymap.set("n", "<C-S-k>", function()
        require("herdr-splits").resize_up()
    end, { desc = "herdr-splits - resize up" })
    vim.keymap.set("n", "<C-S-l>", function()
        require("herdr-splits").resize_right()
    end, { desc = "herdr-splits - resize right" })
else
    ---@diagnostic disable: missing-fields
    vim.pack.add(require("load").gh({ "mrjones2014/smart-splits.nvim" }))
    require("smart-splits").setup({})

    vim.keymap.set("n", "<C-S-h>", function()
        require("smart-splits").resize_left()
    end, { desc = "smart-splits - resize left" })
    vim.keymap.set("n", "<C-S-j>", function()
        require("smart-splits").resize_down()
    end, { desc = "smart-splits - resize down" })
    vim.keymap.set("n", "<C-S-k>", function()
        require("smart-splits").resize_up()
    end, { desc = "smart-splits - resize up" })
    vim.keymap.set("n", "<C-S-l>", function()
        require("smart-splits").resize_right()
    end, { desc = "smart-splits - resize right" })
    vim.keymap.set("n", "<C-h>", function()
        require("smart-splits").move_cursor_left()
    end, { desc = "smart-splits - move cursor left" })
    vim.keymap.set("n", "<C-j>", function()
        require("smart-splits").move_cursor_down()
    end, { desc = "smart-splits - move cursor down" })
    vim.keymap.set("n", "<C-k>", function()
        require("smart-splits").move_cursor_up()
    end, { desc = "smart-splits - move cursor up" })
    vim.keymap.set("n", "<C-l>", function()
        require("smart-splits").move_cursor_right()
    end, { desc = "smart-splits - move cursor right" })
    vim.keymap.set("n", "<leader>bh", function()
        require("smart-splits").swap_buf_left()
    end, { desc = "smart-splits - swap buffer left" })
    vim.keymap.set("n", "<leader>bj", function()
        require("smart-splits").swap_buf_down()
    end, { desc = "smart-splits - swap buffer down" })
    vim.keymap.set("n", "<leader>bk", function()
        require("smart-splits").swap_buf_up()
    end, { desc = "smart-splits - swap buffer up" })
    vim.keymap.set("n", "<leader>bl", function()
        require("smart-splits").swap_buf_right()
    end, { desc = "smart-splits - swap buffer right" })
end
